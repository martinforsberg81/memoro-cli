describe('mc deploy — the disk (disk-pressure.js)', () => {
  /** The shared policy on a fake disk and in-memory state: `frees` is what one tidy step gives back. */
  function fakeDisk(free, { frees = 0 } = {}) {
    const files = {};
    const disk = { free, ran: 0, files };
    disk.policy = createDiskPressure({
      path: '/w/runner/scratch', stateDir: '/w/runner',
      freeBytes: () => { if (disk.free instanceof Error) throw disk.free; return disk.free; },
      read: (path) => files[path] ?? null, writeJson: (path, value) => { files[path] = JSON.stringify(value); },
      now: () => Date.parse('2026-11-05T12:00:00Z'),
      steps: [{ name: 'tidy', run: async () => { disk.ran += 1; disk.free += frees; return { ok: true, removed: 1, kept: [], errors: [] }; } }],
    });
    return disk;
  }

  it('too little or unknown space keeps the deploy script unspawned, and the row and the terminal say why', async () => {
    for (const [free, said] of [
      [15e9, /^mc: disk: 15\.0 GB free — the deploy script not started: below 20\.0 GB after tidying; safe candidates are exhausted — nothing was deployed$/mu],
      [new Error('EIO'), /^mc: disk: unknown free — the deploy script not started: free space could not be measured — nothing was deployed$/mu],
    ]) {
      work = mkdtempSync(join(tmpdir(), 'mc-deploy-work-'));
      const disk = fakeDisk(free);
      let spawned = 0;
      const { out, stdout, stderr } = io();
      const code = await run([], { ...deps({ disk: disk.policy, spawnDeploy: async () => { spawned += 1; return { code: 0 }; } }), stdout, stderr });
      assert.equal(code, 1);
      assert.equal(spawned, 0, 'no script');
      assert.match(out.stderr, said);
      const [row] = readDeploys({ MC_WORK_ROOT: work });
      assert.deepEqual([row.outcome, row.stopped_at], ['failed', 'disk']);
    }
  });

  it('a pressure pass that restores 20 GB lets the script go, and the monitor reads every minute while it runs without stopping it', async () => {
    const disk = fakeDisk(19e9, { frees: 12e9 });
    const timers = [];
    let finish;
    let started;
    let heldAtSpawn = false;
    const running = new Promise((resolve) => { started = resolve; });
    const { stdout, stderr } = io();
    const shipped = run([], {
      ...deps({
        disk: disk.policy,
        every: (ms, fn) => { const timer = { ms, fn, stopped: false }; timers.push(timer); return () => { timer.stopped = true; }; },
        spawnDeploy: () => new Promise((resolve) => {
          heldAtSpawn = disk.policy.readState()?.admission_lease?.trigger === 'deploy';
          finish = resolve; started();
        }),
      }),
      stdout, stderr,
    });
    await running;
    assert.equal(disk.ran, 1, 'the pass before the spawn');
    assert.equal(heldAtSpawn, true, 'spawn is inside admission exclusion');
    assert.equal(disk.policy.readState().admission_lease, null, 'running deploy does not hold admission');
    assert.deepEqual(timers.map((timer) => timer.ms), [60_000]);
    disk.free = 17e9;
    await timers[0].fn();
    assert.equal(disk.ran, 2, 'below 20 GB during the deploy: a pass at once');
    const events = JSON.parse(disk.files['/w/runner/disk-pressure-events.json']);
    assert.deepEqual(events.map((event) => [event.trigger, event.before_bytes, event.after_bytes]), [['deploy', 19e9, 31e9], ['deploy-monitor', 17e9, 29e9]]);
    assert.equal(timers[0].stopped, false, 'the deploy is not stopped for it');
    finish({ code: 0 });
    assert.equal(await shipped, 0);
    assert.equal(timers[0].stopped, true, 'the monitor ends with the script');
  });

  it('admission held by another mc process is waited for, bounded, and only a lease still held then refuses', async () => {
    const busy = { admitted: false, busy: true, available: 312e9, reason: 'pid 336571 is admitting work', line: 'disk: 312.1 GB free — the deploy script not started: pid 336571 is admitting work' };
    for (const [busyFor, expected] of [[3, 0], [Infinity, 1]]) {
      work = mkdtempSync(join(tmpdir(), 'mc-deploy-work-'));
      let asked = 0;
      let now = 0;
      let spawned = 0;
      const disk = {
        admit: async () => { asked += 1; return asked <= busyFor ? busy : { admitted: true, available: 312e9, reason: null, release: () => {} }; },
        poll: async () => null,
      };
      const { out, stdout, stderr } = io();
      const code = await run([], {
        ...deps({ disk, every: () => () => {}, spawnDeploy: async () => { spawned += 1; return { code: 0 }; } }),
        sleep: async (ms) => { now += ms; }, clock: () => now, stdout, stderr,
      });
      assert.equal(code, expected);
      assert.equal(spawned, expected === 0 ? 1 : 0);
      assert.equal(out.stdout.match(/mc: waiting for the disk admission — pid 336571 is admitting work/gu)?.length, 1, 'said once');
      if (expected === 1) {
        assert.ok(now >= DISK_BUSY_WAIT_MS, 'refused only after the bound');
        assert.match(out.stderr, /pid 336571 is admitting work — nothing was deployed/u);
        const [row] = readDeploys({ MC_WORK_ROOT: work });
        assert.deepEqual([row.outcome, row.stopped_at], ['failed', 'disk']);
      } else assert.equal(asked, 4);
    }
  });
});

