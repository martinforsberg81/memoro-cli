/**
 * The gate's two measurements with nothing real behind them: the run history
 * and `fullRun` for the first, the shared checkout's server and the suite
 * runner for the second. `calls` records what was started, so a refusal can say
 * that nothing was — above all, that the deploy script never was.
 *
 * `served` is the commit the fake server says it was built from; `outcomes` is
 * what each declared suite does (`ok`, `red`, `skip`, `unmeasured`).
 */
function gateFake({
  runs = [fullRunOf()], started = null, mends = [], suites = ['smoke'], outcomes = {}, served = SHA, declared = null,
  appError = null, dirtyNow = [], servedDirty = undefined,
  head = SHA, branch = '', contained = true, held = {}, shown = null, checkoutFails = false, revive = null,
  staticServed = null, runner = null, origin = SHA, existing = [], place = null,
} = {}) {
  const calls = {
    fullRun: [], history: 0, servers: [], statics: [], suites: [], mends: 0, git: [], holds: [], follows: 0, ensures: [], sleeps: [], order: [],
    placed: [], stopped: [], ensuredIn: [],
  };
  // The servers the registry would list for mc's own deploy worktree: the ones already there, then those an ensure starts.
  const live = [...existing];
  const declaration = declared || { suites: suites.map((name) => ({ name })), environments: { dev: { service: 'app' } } };
  // The checkout, as the exercise places it: `checkout --detach` moves it, and the
  // fake servers are built from wherever it stands when they are (re)started.
  const checkout = { head };
  const measured = [];
  const declarationText = (at) => shown?.[at] ?? JSON.stringify({
    schema_version: 1,
    ...declaration,
    suites: declaration.suites.map((suite) => ({ argv: ['node', `${suite.name}.js`], ...suite })),
  });
  const gitIn = (worktree, args) => {
    calls.git.push({ worktree, args });
    calls.order.push(`git:${args[0]}`);
    const out = (status = 0, stdout = '', stderr = '') => ({ status, stdout, stderr });
    if (args[0] === 'show') return out(0, declarationText(args[1].split(':')[0]));
    if (args[0] === 'branch') return out(0, `${branch}\n`);
    if (args[0] === 'merge-base') return contained ? out(0) : out(1);
    if (args[0] === 'checkout') {
      if (checkoutFails) return out(1, '', 'error: cannot detach');
      checkout.head = args[2];
      return out(0);
    }
    return out(1, '', 'not faked');
  };
  // What an ensure that is not pinned does to the checkout, as `followMain` does: fast-forwards it to origin/main.
  // The shared route's checkout only: an ensure for any other worktree (mc's own deploy worktree) has no main to follow.
  const SHARED = '/tmp/does-not-exist/shared/memoro';
  const follow = (pinned, worktree = SHARED) => { if (!pinned && worktree === SHARED) { calls.follows += 1; checkout.head = origin; } };
  const startedServer = (service) => {
    const id = `${service}-${live.length + 1}`;
    live.push({ instance_id: id, service, worktree_path: 'own' });
    return id;
  };
  const resultOf = (name) => {
    const how = outcomes[name] || 'ok';
    return {
      name, ok: how === 'ok' || how === 'skip', unmeasured: how === 'unmeasured', skipped: how === 'skip',
      status: how === 'ok' ? 0 : how === 'skip' ? 78 : 1, seconds: 3, tail: outcomes[`${name}:tail`] || `${name} said ${how}\n`,
    };
  };
  const gate = {
    history: () => { calls.history += 1; return { runs: [...runs, ...measured] }; },
    // A full run the gate measured is in the history from then on, as the real one writes it.
    fullRun: async (repo) => { calls.fullRun.push(repo); const run = started || fullRunOf(SHA); measured.push(run); return run; },
    readMends: () => { calls.mends += 1; return mends; },
    root: work,
    mendRoot: work,
  };
  const suiteDeps = {
    sharedWorktree: () => SHARED,
    readDeclaration: () => ({ ok: true, declaration }),
    gitIn,
    servingWorktree: (worktree, { service }) => held[service] || null,
    mainHold: (server, { now, idleMs }) => { calls.order.push('hold'); calls.holds.push({ id: server.instance_id, now, idleMs }); return server.hold ? (typeof server.hold === 'function' ? server.hold(now) : server.hold) : null; },
    now: () => calls.clock ?? 0,
    sleep: async (ms) => { calls.sleeps.push(ms); calls.clock = (calls.clock ?? 0) + ms; },
    ensureAppServer: async (worktree, declared, options = {}) => {
      calls.ensures.push({ tier: 'app', pin: options.deps?.pin === true, head: checkout.head });
      calls.ensuredIn.push(worktree);
      follow(options.deps?.pin === true, worktree);
      if (appError) return { ok: false, error: appError };
      const commit = revive && calls.servers.length ? revive(calls.servers.length) : (served === 'checkout' ? checkout.head : served);
      calls.servers.push({ worktree, commit });
      startedServer('app');
      const builtFrom = servedDirty === undefined ? { commit } : { commit, dirty: servedDirty };
      return { ok: true, server: { built_from: builtFrom, health_url: 'http://127.0.0.1:1/api/version' }, baseUrl: 'http://127.0.0.1:1' };
    },
    ensureDevServer: async (worktree, declared, options = {}) => {
      calls.ensures.push({ tier: 'static', pin: options.pin === true, head: checkout.head });
      calls.ensuredIn.push(worktree);
      follow(options.pin === true, worktree);
      if (staticServed === null) return { ok: false, error: 'no static tier in this test' };
      const commit = staticServed === 'checkout' ? checkout.head : typeof staticServed === 'function' ? staticServed(calls.statics.length) : staticServed;
      calls.statics.push({ worktree, commit });
      startedServer('static');
      return { ok: true, server: { url: 'http://127.0.0.1:2/', instance_id: 'static-1', built_from: { commit } } };
    },
    tokenFor: async () => ({ name: null, token: null, from: null }),
    head: () => checkout.head,
    dirty: () => dirtyNow,
    // mc's own deploy worktree: placed at the pick by the function ship uses (the placing itself is
    // tested in its own cases), the servers the registry lists, and the stopping of those.
    placeWorktree: ({ worktree, sha }) => {
      calls.placed.push({ worktree, sha });
      if (place) return place({ worktree, sha });
      const from = checkout.head;
      checkout.head = sha;
      return { ok: true, moved: from !== sha, how: from !== sha ? 'reset' : null, strays: [], restored: [], from };
    },
    serversFor: () => live.map((server) => ({ ...server })),
    stopServer: (server) => {
      calls.stopped.push(server.instance_id);
      live.splice(live.findIndex((one) => one.instance_id === server.instance_id), 1);
      return { ok: true, instance_id: server.instance_id };
    },
    holderLock: (root, fn) => fn(),
    answers: async () => true,
    runSuites: async (options) => {
      const { declaration: declared, worktree } = options;
      calls.suites.push({ worktree, names: declared.suites.map((suite) => suite.name) });
      // A runner of the test's own: a suite that finds its server gone calls `revive`, as the real one does.
      if (runner) return runner(options, resultOf, calls, checkout);
      return { results: declared.suites.map((suite) => resultOf(suite.name)), gone: [], skipped: [] };
    },
  };
  return { gate, suites: suiteDeps, calls, checkout };
}

/**
 * The register's lock with something that happens just before the deploy's
 * admission takes it: after the gate has passed, before the admission. Once
 * the verb stopped asking nobody stands between the two, so a test makes the
 * race through this lock; `raced.ran` says that the racing step really ran. The
 * preparation's own lock (`deploy-prepare`) is passed through untouched.
 */
function lockWithRace(race) {
  const raced = { ran: 0 };
  const lock = (root, fn, options) => {
    if (options?.name === 'deploy') { raced.ran += 1; race(); }
    return realLock(root, fn, options);
  };
  return { lock, raced };
}

/**
 * A refusing admission: the stop for a test that has to end after the gate
 * passed and before anything ships (where such a test once answered no at the
 * question). A language run, by this test process, starts at the admission
 * under the lock, so the admission refuses with exit 1 and no deployer starts;
 * `end()` ends that run again, so a later run in the same test is not refused
 * before it reads the preparation. `raced.ran` counts the admissions reached.
 * Its `startDeployer` only counts (`started`) and ships nothing, so an
 * admission that fails to refuse makes the test red, never a deploy that runs.
 */
function refusingAdmission() {
  const env = { MC_WORK_ROOT: work };
  let current = null;
  const { lock, raced } = lockWithRace(() => {
    current = startRun({ manifest: 'stop-at-admission', lang: 'sv', pid: process.pid }, env);
  });
  const end = () => {
    if (current) endRun(current, { outcome: 'done' }, env);
    current = null;
  };
  const started = [];
  const startDeployer = (job) => { started.push(job); return { pid: process.pid, inline: () => 0 }; };
  return { lock, raced, end, started, startDeployer };
}

